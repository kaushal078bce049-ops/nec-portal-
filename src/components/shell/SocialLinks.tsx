export function SocialLinks({
  links,
  className = '',
  size = 'md',
}: {
  links: SocialLink[];
  className?: string;
  size?: 'sm' | 'md';
}) {
  if (links.length === 0) return null;
  const px = size === 'sm' ? 16 : 18;

  return (
    <ul className={`flex flex-wrap items-center gap-2 ${className}`}>
      {links.map((link) => (
        <li key={link.label}>
          <a
            href={link.url}
            target="_blank"
            // noopener protects window.opener; noreferrer keeps the referrer off
            // third-party analytics.
            rel="noopener noreferrer"
            className="social-btn"
            title={link.label}
            aria-label={`${link.label} (opens in a new tab)`}
          >
            <svg
              width={px}
              height={px}
              viewBox="0 0 24 24"
              fill="currentColor"
              aria-hidden="true"
              focusable="false"
            >
              <path d={PATHS[link.icon] ?? PATHS.website} />
            </svg>
          </a>
        </li>
      ))}
    </ul>
  );
}
